# ---------------------------------------------------------------- layer block models
$bb = Get-Content -Raw $bbPath | ConvertFrom-Json
$nameToKey = @{
    'grill_housing.png' = 'housing'
    'grill_plate.png'   = 'plate'
    'grill_trim.png'    = 'trim'
    'grill_emitter.png' = 'emitter'
    'grill_dark.png'    = 'dark'
    'grill_screw.png'   = 'screw'
    'grill_label.png'   = 'label'
}
$indexToKey = @()
foreach ($texture in $bb.textures) { $indexToKey += $nameToKey[$texture.name] }

$textures = [ordered]@{
    particle = 'ntmdoors:blocks/emancipation_grill_housing'
    housing  = 'ntmdoors:blocks/emancipation_grill_housing'
    plate    = 'ntmdoors:blocks/emancipation_grill_plate'
    trim     = 'ntmdoors:blocks/emancipation_grill_trim'
    emitter  = 'ntmdoors:blocks/emancipation_grill_emitter'
    dark     = 'ntmdoors:blocks/emancipation_grill_dark'
    screw    = 'ntmdoors:blocks/emancipation_grill_screw'
    label    = 'ntmdoors:blocks/emancipation_grill_label'
}

$faceNames = @('north', 'east', 'south', 'west', 'up', 'down')
$layers = @(
    [pscustomobject]@{ Name = 'bottom'; File = 'emancipation_grill';        Model = 'emancipation_grill_bottom'; Base = 0.0;  Top = 16.0 },
    [pscustomobject]@{ Name = 'middle'; File = 'emancipation_grill_middle'; Model = 'emancipation_grill_middle'; Base = 16.0; Top = 32.0 },
    [pscustomobject]@{ Name = 'top';    File = 'emancipation_grill_top';    Model = 'emancipation_grill_top';    Base = 32.0; Top = 48.0 }
)
$layerElements = @{}
foreach ($layer in $layers) {
    $layerElements[$layer.Name] = New-Object System.Collections.ArrayList
}

foreach ($el in $bb.elements) {
    $x1 = [double]$el.from[0]
    $y1 = [double]$el.from[1]
    $z1 = [double]$el.from[2]
    $x2 = [double]$el.to[0]
    $y2 = [double]$el.to[1]
    $z2 = [double]$el.to[2]

    foreach ($layer in $layers) {
        $base = [double]$layer.Base
        $top = [double]$layer.Top
        $ya = [Math]::Max($y1, $base)
        $yb = [Math]::Min($y2, $top)
        if ($yb -le $ya) { continue }

        $faces = [ordered]@{}
        foreach ($faceName in $faceNames) {
            $prop = $el.faces.PSObject.Properties[$faceName]
            if ($null -eq $prop) { continue }
            $face = $prop.Value

            # Horizontal caps belong only to the slice that contains the parent top/bottom.
            if ($faceName -eq 'up' -and -not ($y2 -gt $base -and $y2 -le $top)) { continue }
            if ($faceName -eq 'down' -and -not ($y1 -ge $base -and $y1 -lt $top)) { continue }

            $u1 = [double]$face.uv[0]
            $v1 = [double]$face.uv[1]
            $u2 = [double]$face.uv[2]
            $v2 = [double]$face.uv[3]

            # Vertical side faces use the matching vertical slice of the source texture.
            if (($faceName -eq 'north' -or $faceName -eq 'east' -or
                 $faceName -eq 'south' -or $faceName -eq 'west') -and
                ($ya -ne $y1 -or $yb -ne $y2)) {
                $height = $y2 - $y1
                if ($height -gt 0) {
                    $origV1 = [double]$face.uv[1]
                    $origV2 = [double]$face.uv[3]
                    $tTop = ($y2 - $yb) / $height
                    $tBottom = ($y2 - $ya) / $height
                    $v1 = $origV1 + $tTop * ($origV2 - $origV1)
                    $v2 = $origV1 + $tBottom * ($origV2 - $origV1)
                }
            }

            $key = $indexToKey[[int]$face.texture]
            $faces[$faceName] = [ordered]@{
                uv      = @(
                    [Math]::Round($u1, 4),
                    [Math]::Round($v1, 4),
                    [Math]::Round($u2, 4),
                    [Math]::Round($v2, 4)
                )
                texture = "#$key"
            }
        }

        if ($faces.Count -eq 0) { continue }
        [void]$layerElements[$layer.Name].Add([ordered]@{
            from  = @(
                [Math]::Round($x1, 4),
                [Math]::Round($ya - $base, 4),
                [Math]::Round($z1, 4)
            )
            to    = @(
                [Math]::Round($x2, 4),
                [Math]::Round($yb - $base, 4),
                [Math]::Round($z2, 4)
            )
            faces = $faces
        })
    }
}

# The old full-height model predates the layer split; remove it so it cannot be loaded by accident.
Remove-Item (Join-Path $blockModels 'emancipation_grill.json') -Force -ErrorAction SilentlyContinue

foreach ($layer in $layers) {
    $model = [ordered]@{
        parent    = 'block/block'
        gui_light = 'front'
        textures  = $textures
        elements  = $layerElements[$layer.Name]
    }
    $json = $model | ConvertTo-Json -Depth 100
    [System.IO.File]::WriteAllText(
        (Join-Path $blockModels ($layer.Model + '.json')),
        $json,
        (New-Object System.Text.UTF8Encoding($false))
    )

    # Mirror the layer's geometry in X. Face UVs stay as-is so the warning sign remains readable.
    $mirrored = $json | ConvertFrom-Json
    foreach ($element in $mirrored.elements) {
        $fromX = [double]$element.from[0]
        $toX = [double]$element.to[0]
        $element.from[0] = [Math]::Round(16.0 - $toX, 4)
        $element.to[0] = [Math]::Round(16.0 - $fromX, 4)
    }
    $mirroredJson = $mirrored | ConvertTo-Json -Depth 100
    [System.IO.File]::WriteAllText(
        (Join-Path $blockModels ($layer.Model + '_mirrored.json')),
        $mirroredJson,
        (New-Object System.Text.UTF8Encoding($false))
    )

    $normal = "ntmdoors:$($layer.Model)"
    $mirror = "ntmdoors:$($layer.Model)_mirrored"
    $variants = @(
        "  `"facing=north,mirrored=false`": { `"model`": `"$normal`" },",
        "  `"facing=east,mirrored=false`":  { `"model`": `"$normal`", `"y`": 90 },",
        "  `"facing=south,mirrored=false`": { `"model`": `"$normal`", `"y`": 180 },",
        "  `"facing=west,mirrored=false`":  { `"model`": `"$normal`", `"y`": 270 },",
        "  `"facing=north,mirrored=true`":  { `"model`": `"$mirror`" },",
        "  `"facing=east,mirrored=true`":   { `"model`": `"$mirror`", `"y`": 90 },",
        "  `"facing=south,mirrored=true`":  { `"model`": `"$mirror`", `"y`": 180 },",
        "  `"facing=west,mirrored=true`":   { `"model`": `"$mirror`", `"y`": 270 }"
    ) -join "`r`n"
    $state = "{`r`n  `"variants`": {`r`n$variants`r`n  }`r`n}`r`n"
    [System.IO.File]::WriteAllText(
        (Join-Path $blockstates ($layer.File + '.json')),
        $state,
        (New-Object System.Text.UTF8Encoding($false))
    )
}

