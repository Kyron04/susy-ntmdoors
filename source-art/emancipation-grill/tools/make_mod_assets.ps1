function Set-Px($bmp, [int]$x, [int]$y, [int]$r, [int]$g, [int]$b, [int]$a = 255) {
    $bmp.SetPixel($x, $y, [System.Drawing.Color]::FromArgb($a, $r, $g, $b))
}

